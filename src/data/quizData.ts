/**
 * Deterministically returns 5 fresh, authentic quiz questions for each day of the year.
 * Rotates cleanly at 12:00 AM Bangladesh Time (Asia/Dhaka) every single day.
 * Functions seamlessly whether device is online or offline.
 */
export function getDailyQuizQuestions(date: Date = new Date(), count: number = 5): QuizQuestion[] {
  const { year, month, day } = getBangladeshDate(date);
  
  // Hash seed for consistent day-of-year rotation
  const seed = (year * 372) + (month * 31) + day;
  const total = AUTHENTIC_QUIZ_QUESTIONS.length;
  
  const selected: QuizQuestion[] = [];
  const chosenIndices = new Set<number>();

  for (let i = 0; i < count; i++) {
    let index = (seed + i * 7) % total;
    while (chosenIndices.has(index)) {
      index = (index + 1) % total;
    }
    chosenIndices.add(index);
    selected.push(AUTHENTIC_QUIZ_QUESTIONS[index]);
  }

  return selected;
}
